function minutesAgoIso(minutes: number): string {
  return new Date(Date.now() - minutes * 60_000).toISOString();
}

function formatTimeHHMM(minutesAgo: number): string {
  const d = new Date(Date.now() - minutesAgo * 60_000);
  return d.toLocaleTimeString('id-ID', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  });
}

export function createDemoSiemEvent(
  actionTaken: AttackAction,
  attackVector: AttackVector,
  severity: Severity
): LiveAttackEvent {
  const id = `SIEM-DEMO-${Math.floor(1000 + Math.random() * 9000)}`;
  const isDetect = actionTaken === 'DETECTED';
  return {
    event_id: id,
    timestamp: new Date().toISOString(),
    source_ip: isDetect ? '185.220.101.44' : '45.146.164.110',
    source_country: isDetect ? 'DE' : 'NL',
    source_coords: isDetect ? [10.45, 51.16] : [5.29, 52.13],
    target_asset: isDetect
      ? 'https://portal.example-corp.test/api/v1/beneficiary'
      : 'https://portal.example-corp.test/login',
    attack_vector: attackVector,
    severity,
    action_taken: actionTaken,
    payload_snippet: isDetect
      ? "GET /api/v1/beneficiary?id=1' OR '1'='1' UNION SELECT * FROM account_registry--"
      : 'POST /login HTTP/2 (142 failed attempts in 60s · user=operator_demo@example-corp.test)',
  };
}

